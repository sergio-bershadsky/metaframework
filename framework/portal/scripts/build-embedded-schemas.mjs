#!/usr/bin/env node
/**
 * Vendor the framework's own eight meta-schemas into the portal's own bundle.
 *
 * Every artifact the framework tells an author to write opens with a `$schema`
 * on the canonical host. Until now only *this* repository's portal could answer
 * one, because the only bytes behind those URLs are eight `schema.json` files
 * under `solutions/metaframework/product/specification/datamodel/`, and a
 * catalog that is not this repository has no `metaframework` solution at all.
 * So the framework's first authoring instruction was a dead link in every
 * catalog but its own. This generator is how the bytes travel.
 *
 * ## Why a generated module and not a file read at runtime
 *
 * The package ships `.next/standalone/` and `bin/*.mjs` and nothing else, so a
 * file only reaches a user's install if it is *inside* the compiled server. Two
 * of the three obvious ways of putting it there do not survive:
 *
 *  - `next.config.ts` excludes `src/**` from output file tracing, so a runtime
 *    `readFile` under `src/` is dropped from the standalone build with no error
 *    — a 404 in someone else's install and a green build here.
 *  - `bin/metaframework.mjs` imports the server in-process without `chdir`, so
 *    at runtime `process.cwd()` is the *user's catalog directory*. A path built
 *    from it works on the author's laptop and nowhere else.
 *  - `import doc from './x.json'` survives, but Turbopack re-serialises the JSON
 *    into a JS object literal: the document served would no longer be the
 *    document reviewed, and the route's content ETag would hash bytes that exist
 *    nowhere on disk. `build-schema-site.mjs` refuses that trade ("a courier,
 *    not an editor") and so does this.
 *
 * String literals in a `.ts` module travel inside the chunk, verbatim, and are
 * the one shape that keeps the bytes.
 *
 * ## Nothing here decides policy
 *
 * `collect`, `SERVED_DIR` and `CANONICAL_SCHEMA_HOST` are imported from
 * `build-schema-site.mjs` rather than restated, so this is a second *consumer*
 * of that scope and not a second scope. All three of its refusals — not valid
 * JSON, no `$id`, an `$id` that disagrees with the URL the document would be
 * served at — fire here unchanged, and `SERVED_DIR` stays the constant it is for
 * the reason written into that script: a policy that can be widened by a
 * command-line flag is not one.
 *
 * ## Run it by hand
 *
 * Not from `prepack`. Generating at publish time would let the bytes that ship
 * differ from the bytes that were reviewed, with nobody seeing a diff. What
 * makes "by hand" safe is `build-embedded-schemas.test.mjs`, which re-renders
 * this module on every `npm test` and fails on any difference — the same
 * arrangement `src/lib/protocol/state-machine-document.schema.json` already has.
 *
 * Usage:  node framework/portal/scripts/build-embedded-schemas.mjs [--check]
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { CANONICAL_SCHEMA_HOST, REPO_ROOT, SERVED_DIR, collect } from './build-schema-site.mjs'

/** The generated module, absolute. The one file this script writes. */
export const EMBEDDED_MODULE = path.join(
  REPO_ROOT,
  'framework/portal/src/lib/schema/embedded.ts',
)

/**
 * A schema's bytes as the inside of a template literal.
 *
 * A template literal is used rather than a quoted one-liner so the checked-in
 * module diffs the way the schemas it copies do — a changed `description` shows
 * up as a changed line, not as one 16 KB line that changed somewhere.
 *
 * The `\r` case is not hypothetical padding: a template literal *normalises*
 * CRLF to LF in its value, so on a CRLF checkout the embedded copy would
 * silently lose the CR and stop being a copy. Escaping it keeps the round-trip
 * exact wherever the file was checked out.
 */
export function escapeTemplate(body) {
  return body
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${')
    .replace(/\r/g, '\\r')
}

const HEADER = `/**
 * The framework's own meta-schemas, carried inside the portal's own bundle.
 *
 * GENERATED by \`framework/portal/scripts/build-embedded-schemas.mjs\` from
 * \`solutions/metaframework/product/specification/datamodel/<name>/schema.json\`.
 * Edit those and re-run it. Do not edit this file: its generator's test
 * re-renders it on every \`npm test\` and compares byte for byte, so a hand-edit
 * is a red suite rather than a copy that has quietly stopped being one.
 *
 * These eight exist here because a catalog that is not this repository has no
 * \`metaframework\` solution, and therefore nothing to answer the \`$schema\` URL
 * every artifact it holds declares. Identity stays global and singular on the
 * canonical host; retrieval becomes local *everywhere*, not just here
 * (\`src/app/schemas/[...path]/route.ts\`).
 *
 * The key is the catalog-relative directory the document is served at, which is
 * its \`$id\` minus the canonical host — checked rather than assumed, by the
 * generator's inherited refusal to embed a document whose \`$id\` disagrees with
 * where it would be served.
 */

/**
 * Look-ups are keyed by a path taken from a request, so a miss is the ordinary
 * case and the value type says so.
 *
 * The table has no prototype, which is what makes that type true. A plain object
 * literal answers \`constructor\` and \`toString\` with a function, so a request
 * for one of those names would hand a function to code the type promised a
 * string. The route's SRN gate refuses those paths long before this table is
 * reached and \`Object.create(null)\` is therefore belt and braces — but a table
 * whose declared type is honest on its own does not depend on a gate two blocks
 * away staying exactly as strict as it is today.
 */
export const EMBEDDED_META_SCHEMAS: Readonly<Record<string, string | undefined>> =
  Object.assign(Object.create(null), {`

/**
 * The whole module as text. Pure — it reads the catalog and returns a string,
 * writing nothing — so the test can render and compare without a temp file, and
 * can render a synthetic tree to prove the comparison is not vacuous.
 */
export function renderEmbeddedModule(root = REPO_ROOT) {
  const entries = collect(root).map(
    ({ name, body }) => `    '${SERVED_DIR}/${name}': \`${escapeTemplate(body)}\`,`,
  )
  return `${HEADER}\n${entries.join('\n')}\n  })\n`
}

function main() {
  const rendered = renderEmbeddedModule()
  const rel = path.relative(REPO_ROOT, EMBEDDED_MODULE)

  if (process.argv.includes('--check')) {
    const current = readFileSync(EMBEDDED_MODULE, 'utf8')
    if (current === rendered) {
      process.stdout.write(`${rel} is current\n`)
      return
    }
    process.stderr.write(`${rel} is stale — re-run this script without --check\n`)
    process.exitCode = 1
    return
  }

  writeFileSync(EMBEDDED_MODULE, rendered)
  const count = collect().length
  process.stdout.write(
    `${count} meta-schemas embedded in ${rel} (${rendered.length} bytes), ` +
      `served under ${CANONICAL_SCHEMA_HOST}/${SERVED_DIR}/\n`,
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
