#!/usr/bin/env node
/**
 * The static site behind `schemas.metaframework.dev`.
 *
 * Every datamodel in every catalog carries a `$id` on the canonical host —
 * identity is global and must not vary between a laptop and production
 * (`src/lib/schema/url.ts`). Until something answers at that host those URLs
 * are identifiers and nothing more, which JSON Schema permits and readers
 * reasonably find surprising. This builds the thing that answers.
 *
 * ## Only the framework's own eight
 *
 * `solutions/metaframework/product/specification/datamodel/` and nothing else.
 * The rule is stated in the specification product's own page: *retrieval from
 * the canonical host is global for these eight and local for everything else* —
 * a private catalog's schemas are served by that catalog's own portal under its
 * `SCHEMA_BASE_URL`. Publishing `acme`'s datamodels here would contradict the
 * spec and, worse, publish a company's private architecture to the open web
 * because a build script globbed one directory too many. The scope is asserted
 * below rather than left to a glob.
 *
 * ## Extensionless on purpose
 *
 * The served path is the entity's SRN path verbatim —
 * `/metaframework/product/specification/datamodel/transport-document`, no
 * `.json` — because that is what the `$id` says, and the `$id` is the contract.
 * A static host cannot guess a media type from an absent extension, so
 * `_headers` states it. Everything in that file is copied from the portal's own
 * route (`src/app/schemas/[...path]/route.ts`) so the two deployments answer
 * alike: `application/schema+json`, permissive CORS because the point is that
 * other tools can read it, and a short max-age because a URL addresses the
 * *current* schema and a redeploy must not be shadowed by a stale cache.
 *
 * ## What it refuses to build
 *
 * A schema whose `$id` disagrees with the URL it would be served at is a fatal
 * build error, not a warning. Serving a document that calls itself something
 * other than where it lives is worse than serving nothing: a resolver that
 * fetches it will cache it under the `$id` it read, and every `$ref` in the
 * catalog then points somewhere that does not exist.
 *
 * Usage:  node framework/portal/scripts/build-schema-site.mjs [--out dir]
 */

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** Repository root: three levels up from `framework/portal/scripts/`. */
export const REPO_ROOT = path.resolve(fileURLToPath(new URL('../../..', import.meta.url)))

/** The canonical host, restated from `src/lib/schema/url.ts`. */
export const CANONICAL_SCHEMA_HOST = 'https://schemas.metaframework.dev'

/**
 * The one directory this site serves, catalog-relative. Not a glob and not a
 * parameter: the scope IS the policy, and a policy that can be widened by a
 * command-line flag is not one.
 */
export const SERVED_DIR = 'metaframework/product/specification/datamodel'

/** Default output, relative to the repository root. Git-ignored. */
export const DEFAULT_OUT = 'dist/schemas'

const ARTIFACT = 'schema.json'

/**
 * Headers, verbatim in intent from the portal's `/schemas` route so a client
 * cannot tell the two apart. Cloudflare Pages reads this file at the site root.
 */
const HEADERS = `# Generated by framework/portal/scripts/build-schema-site.mjs — do not edit.
#
# Mirrors framework/portal/src/app/schemas/[...path]/route.ts so this static
# deployment and the portal's own route answer alike.

/${SERVED_DIR}/*
  Content-Type: application/schema+json; charset=utf-8
  Cache-Control: public, max-age=300, stale-while-revalidate=3600
  Access-Control-Allow-Origin: *
  Access-Control-Allow-Methods: GET, HEAD, OPTIONS
  X-Content-Type-Options: nosniff
`

/**
 * Every meta-schema to serve: its entity name, the URL it claims, and its bytes.
 *
 * Bytes are passed through unmodified. A schema is a contract and this script
 * is a courier — reformatting it here would mean the document served and the
 * document reviewed are not the same file.
 */
export function collect(root = REPO_ROOT) {
  const dir = path.join(root, 'solutions', SERVED_DIR)
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()

  return names.map((name) => {
    const file = path.join(dir, name, ARTIFACT)
    const body = readFileSync(file, 'utf8')
    const url = `${CANONICAL_SCHEMA_HOST}/${SERVED_DIR}/${name}`

    let declared
    try {
      declared = JSON.parse(body).$id
    } catch (error) {
      throw new Error(`${name}/${ARTIFACT} is not valid JSON: ${error.message}`)
    }
    if (declared !== url) {
      throw new Error(
        `${name}/${ARTIFACT} would be served at ${url} but its $id says ${declared ?? '(absent)'}. ` +
          'A document that calls itself something other than where it lives poisons every resolver ' +
          'that fetches it; fix the $id or move the entity.',
      )
    }

    return { name, url, body, title: JSON.parse(body).title ?? name }
  })
}

/** A plain index, so the site root is a readable page rather than a 404. */
function indexPage(schemas) {
  const rows = schemas
    .map(
      ({ name, title }) =>
        `      <li><a href="/${SERVED_DIR}/${name}"><code>${name}</code></a> — ${escapeHtml(title)}</li>`,
    )
    .join('\n')

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>metaframework schemas</title>
    <style>
      :root { color-scheme: dark light }
      body { margin: 0 auto; max-width: 46rem; padding: 3rem 1.5rem;
             font: 15px/1.65 ui-sans-serif, system-ui, sans-serif }
      code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 0.92em }
      li { margin: 0.35rem 0 }
      p { opacity: 0.8 }
    </style>
  </head>
  <body>
    <h1>metaframework schemas</h1>
    <p>
      The canonical identities of the metaframework's own artifact formats. Each URL is what a
      conforming file names in its <code>$schema</code> header, and what this host answers with.
    </p>
    <ul>
${rows}
    </ul>
    <p>
      These eight are the framework's own. A private catalog's datamodels keep their identity on this
      host but are served by that catalog's own portal — identity is global, retrieval is local.
    </p>
  </body>
</html>
`
}

const escapeHtml = (text) =>
  String(text).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])

export function build({ root = REPO_ROOT, out = DEFAULT_OUT } = {}) {
  const schemas = collect(root)
  const target = path.isAbsolute(out) ? out : path.join(root, out)

  rmSync(target, { recursive: true, force: true })
  const served = path.join(target, SERVED_DIR)
  mkdirSync(served, { recursive: true })

  for (const { name, body } of schemas) writeFileSync(path.join(served, name), body)
  writeFileSync(path.join(target, '_headers'), HEADERS)
  writeFileSync(path.join(target, 'index.html'), indexPage(schemas))

  return { target, schemas }
}

function main() {
  const flag = process.argv.indexOf('--out')
  const out = flag === -1 ? DEFAULT_OUT : process.argv[flag + 1]
  const { target, schemas } = build({ out })
  const rel = path.relative(REPO_ROOT, target) || target
  for (const { name, url } of schemas) process.stdout.write(`  ${name.padEnd(24)} ${url}\n`)
  process.stdout.write(`\n${schemas.length} schemas, _headers and index.html written to ${rel}/\n`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
